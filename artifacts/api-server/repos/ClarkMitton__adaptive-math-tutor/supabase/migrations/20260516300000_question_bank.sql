-- Question bank table: stores display text, answers, and image metadata.
-- The static question-bank.ts remains the source of truth for grade logic.
-- This table adds image_search_term and custom_image_url per question,
-- and allows admin editing of question text and answers.

create table if not exists public.questions (
  id                uuid         primary key default gen_random_uuid(),
  sub_topic_key     text         not null,
  grade             integer      not null check (grade between 1 and 4),
  question_text     text         not null,
  accepted_answers  text[]       not null default '{}',
  image_search_term text,
  custom_image_url  text,
  created_at        timestamptz  not null default now(),
  unique (sub_topic_key, grade)
);

alter table public.questions enable row level security;

-- Service role has full access; no student-facing RLS needed (server functions only)
do $$
begin
  if not exists (
    select 1 from pg_policies where tablename = 'questions' and policyname = 'service_role_questions'
  ) then
    execute $p$
      create policy "service_role_questions" on public.questions
        for all using (true) with check (true)
    $p$;
  end if;
end
$$;

